export const LanguageProvider = ({ children, session }) => {
  const [language, setLanguage] = useState('EN');
  const [isAILoading, setIsAILoading] = useState(false);

  useEffect(() => {
    if (session?.user?.id) {
      const fetchLang = async () => {
        try {
          const { data } = await supabase
            .from('profiles')
            .select('language_preference')
            .eq('id', session.user.id)
            .single();
          if (data?.language_preference) setLanguage(data.language_preference);
        } catch (e) {
          console.warn("Language fetch failed");
        }
      };
      fetchLang();
    }
  }, [session]);

  const t = (key) => {
    if (!key) return '';
    const cleanKey = key.toLowerCase().replace(/ /g, '_');
    return translations[language]?.[key] || translations[language]?.[cleanKey] || 
           translations['EN']?.[key] || translations['EN']?.[cleanKey] || key;
  };

  const setAppLanguage = async (newLang) => {
    setLanguage(newLang);
    if (session?.user?.id) {
      await supabase.from('profiles').update({ language_preference: newLang }).eq('id', session.user.id);
    }
  };

  const processNLPCommand = async (command, sensorData = null) => {
    setIsAILoading(true);
    const cmd = command.toLowerCase();
    let response = { success: false, message: "I'm still learning that command." };

    try {
      if (cmd.includes('hindi') || cmd.includes('हिंदी')) {
        await setAppLanguage('HI');
        response = { success: true, message: translations['HI'].ai_processing };
      } else if (cmd.includes('kannada') || cmd.includes('ಕನ್ನಡ')) {
        await setAppLanguage('KN');
        response = { success: true, message: translations['KN'].ai_processing };
      } else if (cmd.includes('telegu') || cmd.includes('telugu') || cmd.includes('తెలుగు')) {
        await setAppLanguage('TE');
        response = { success: true, message: translations['TE'].ai_processing };
      } else if (cmd.includes('malayalam') || cmd.includes('മലയാളം')) {
        await setAppLanguage('ML');
        response = { success: true, message: translations['ML'].ai_processing };
      } else if (cmd.includes('english')) {
        await setAppLanguage('EN');
        response = { success: true, message: translations['EN'].ai_processing };
      } else if (sensorData && (
        cmd.includes('health') || cmd.includes('status') || cmd.includes('moisture') || 
        cmd.includes('temp') || cmd.includes('temperature') || cmd.includes('tds') || 
        cmd.includes('nutrient') || cmd.includes('data')
      )) {
        const status = sensorData.classification || 'Stable';
        let msg = '';
        
        if (cmd.includes('temp')) {
          msg = language === 'HI' ? `मिट्टी का तापमान ${sensorData.temperature}°C है।` :
                language === 'KN' ? `ಮಣ್ಣಿನ ತಾಪಮಾನ ${sensorData.temperature}°C ಆಗಿದೆ.` :
                language === 'TE' ? `నేల ఉష్ణోగ్రత ${sensorData.temperature}°C.` :
                language === 'ML' ? `മണ്ണിലെ താപനില ${sensorData.temperature}°C ആണ്.` :
                `The soil temperature is ${sensorData.temperature}°C.`;
        } else if (cmd.includes('tds') || cmd.includes('nutrient')) {
          msg = language === 'HI' ? `पोषक तत्वों का स्तर ${sensorData.tds} ppm है।` :
                language === 'KN' ? `ಪೋಷಕಾಂಶಗಳ ಮಟ್ಟ ${sensorData.tds} ppm ಆಗಿದೆ.` :
                language === 'TE' ? `పోషక విలువల స్థాయి ${sensorData.tds} ppm.` :
                language === 'ML' ? `పോഷక നില ${sensorData.tds} ppm ആണ്.` :
                `The nutrient level is ${sensorData.tds} ppm.`;
        } else {
          msg = language === 'HI' ? `आपकी मिट्टी की नमी ${sensorData.moisture}% है। स्थिति ${status} है।` :
                language === 'KN' ? `ನಿಮ್ಮ ಮಣ್ಣಿನ ತೇವಾಂಶ ${sensorData.moisture}% ಆಗಿದೆ. ಸ್ಥಿತಿ ${status} ಆಗಿದೆ.` :
                language === 'TE' ? `మీ నేల తేమ ${sensorData.moisture}%. స్థితి ${status} గా ఉంది.` :
                language === 'ML' ? `നിങ്ങളുടെ മണ്ണിലെ ഈർപ്പം ${sensorData.moisture}% ആണ്. നില ${status} ആണ്.` :
                `Your soil moisture is ${sensorData.moisture}%. Current status is ${status}.`;
        }
        response = { success: true, message: msg };
      }
    } finally {
      setIsAILoading(false);
    }
    return response;
  };

  return (
    <LanguageContext.Provider value={{ language, setLanguage: setAppLanguage, t, processNLPCommand, isAILoading }}>
      {children}
    </LanguageContext.Provider>
  );
};

export const useLanguage = () => {
  const context = useContext(LanguageContext);
  if (!context) throw new Error('useLanguage must be used within LanguageProvider');
  return context;
};
